"""WD139A deterministic layout generator; CSV is the sole editable mapping.

Usage: python gen_layout.py nodes.csv output_directory
Generated files are intentionally not installed by this tool.
"""
import csv,hashlib,json,sys
from pathlib import Path

def generate(source, out):
    raw=source.read_text(encoding='utf-8-sig')
    lines=[line for line in raw.splitlines() if line.strip() and not line.lstrip().startswith('#')]
    reader=csv.DictReader(lines,skipinitialspace=True)
    required={'index','node_id','max_rank','bit_offset','bit_width','spec','pool'}
    assert reader.fieldnames and set(k.strip() for k in reader.fieldnames)==required
    rows=[{k.strip():v.strip() for k,v in row.items()} for row in reader]
    for r in rows:
        for k in ('index','node_id','max_rank','bit_offset','bit_width','spec'):r[k]=int(r[k])
    assert 0<len(rows)<=256
    ids=set();bits=set()
    for i,r in enumerate(rows):
        assert r['index']==i and r['spec'] in (-1,0,1,2)
        assert 1<=r['bit_width']<=8 and 0<=r['max_rank']<2**r['bit_width']
        assert r['bit_offset']>=0 and r['pool'] in ('AE','TE','FREE')
        assert (r['node_id']==0)==(r['max_rank']==0)
        if r['node_id']:assert r['node_id'] not in ids;ids.add(r['node_id'])
        covered=set(range(r['bit_offset'],r['bit_offset']+r['bit_width']))
        assert not bits&covered;bits|=covered
    # Frozen digest of the 108 original slots. Never silently move saved bits.
    legacy=hashlib.sha256(json.dumps(rows[:108],separators=(',',':'),sort_keys=True).encode()).hexdigest()
    assert legacy=='6d8c782d8e48c6376c533a8a574372e534633321e4a0fc03a93a77965856f8c6', 'legacy layout drift requires a separately versioned migration'
    count=max(bits)+1
    assert bits==set(range(count)), 'unmapped bits require explicit reserved slots'
    width=(count+3)//4
    digest=hashlib.sha256(json.dumps(rows,separators=(',',':'),sort_keys=True).encode()).hexdigest()
    # 256 nodes is array capacity, NOT 256 bits. One maximum rank byte per node.
    # Current chat commands fit 255; future layouts must chunk before this fails.
    assert len('.wd67save2 2000000000 2 1 '+digest+' '+('f'*width))<=255
    out.mkdir(parents=True,exist_ok=True)
    header='''// Generated by gen_layout.py; edit nodes.csv, not this file.
#pragma once
#include <array>
#include <cstdint>
#include <string>
#include <string_view>
namespace WD139 {
inline constexpr unsigned Version=1, Capacity=256, LegacyBits=120, Count=%d, Bits=%d, HexSize=%d;
inline constexpr char Hash[]="%s";
struct Node { unsigned id, maximum, offset, width; int spec; };
inline constexpr std::array<Node,Count> Nodes={{
'''%(len(rows),count,width,digest)
    header+=',\n'.join('    {%d,%d,%d,%d,%d}'%(r['node_id'],r['max_rank'],r['bit_offset'],r['bit_width'],r['spec'])for r in rows)+'\n}};\n'
    header+='''inline constexpr auto Ids=[] {
    std::array<unsigned,Count> ids{};
    for(unsigned i=0;i<Count;++i)ids[i]=Nodes[i].id;
    return ids;
}();
struct Build {
    std::array<std::uint8_t,Capacity> ranks{};
    bool Empty() const { for(auto rank:ranks) if(rank) return false; return true; }
    bool Valid() const {
        for(unsigned i=0;i<Capacity;++i)
            if(ranks[i]>(i<Count?Nodes[i].maximum:0)) return false;
        return true;
    }
    bool SpecValid(unsigned spec) const {
        if(spec==3) return Empty();
        if(spec>2) return false;
        for(unsigned i=0;i<Count;++i)
            if(ranks[i] && Nodes[i].spec>=0 && unsigned(Nodes[i].spec)!=spec) return false;
        return true;
    }
    std::string Hex() const {
        std::string out(HexSize,'0');
        for(unsigned i=0;i<Count;++i) for(unsigned b=0;b<Nodes[i].width;++b) {
            unsigned pos=Nodes[i].offset+b, j=HexSize-1-pos/4;
            unsigned n=out[j]<='9'?out[j]-'0':out[j]-'a'+10;
            n|=((ranks[i]>>b)&1u)<<(pos%4);out[j]="0123456789abcdef"[n];
        }
        return out;
    }
    static bool ParseHex(std::string_view text,Build& result) {
        if(text.size()!=HexSize) return false;
        std::array<unsigned,HexSize> digits{};
        for(unsigned i=0;i<HexSize;++i) {
            char c=text[HexSize-1-i];
            if(c>='0'&&c<='9') digits[i]=c-'0';
            else if(c>='a'&&c<='f') digits[i]=c-'a'+10;
            else return false;
        }
        if(Bits%4 && digits.back()>=(1u<<(Bits%4))) return false;
        Build candidate;
        for(unsigned i=0;i<Count;++i) for(unsigned b=0;b<Nodes[i].width;++b) {
            unsigned pos=Nodes[i].offset+b;
            candidate.ranks[i]|=((digits[pos/4]>>(pos%4))&1u)<<b;
        }
        if(!candidate.Valid()) return false;
        result=candidate;return true;
    }
    std::string Rows() const {
        std::string out="[";bool first=true;
        for(unsigned i=0;i<Count;++i) if(ranks[i]) {
            if(!first)out+=","; first=false;
            out+="["+std::to_string(Nodes[i].id)+","+std::to_string(ranks[i])+"]";
        }
        return out+"]";
    }
};
} // namespace WD139
'''
    (out/'RebornWitchDoctorNodeLayout.h').write_text(header,encoding='utf-8')
    lua='-- Generated by gen_layout.py; edit nodes.csv.\nRebornWDNodeLayout={version=1,capacity=256,legacyBits=120,count=%d,bits=%d,hexSize=%d,hash="%s",nodes={},index={},maximum={}}\nlocal L=RebornWDNodeLayout\n'%(len(rows),count,width,digest)
    for r in rows:
        lua+='L.nodes[%d]={id=%d,maximum=%d,offset=%d,width=%d,spec=%d}\n'%(r['index'],r['node_id'],r['max_rank'],r['bit_offset'],r['bit_width'],r['spec'])
        if r['node_id']:lua+='L.index[%d]=%d;L.maximum[%d]=%d\n'%(r['node_id'],r['index'],r['node_id'],r['max_rank'])
    (out/'NodeLayout.lua').write_text(lua,encoding='utf-8')
    sql='-- Generated node reference; no character rows are modified.\nCREATE TABLE IF NOT EXISTS reborn_wd_node_def(node_id INT UNSIGNED PRIMARY KEY,max_rank TINYINT UNSIGNED NOT NULL,layout_index SMALLINT UNSIGNED NOT NULL,bit_offset SMALLINT UNSIGNED NOT NULL,bit_width TINYINT UNSIGNED NOT NULL,spec TINYINT NOT NULL) ENGINE=InnoDB;\nINSERT INTO reborn_wd_node_def VALUES\n'
    sql+=',\n'.join('(%d,%d,%d,%d,%d,%d)'%(r['node_id'],r['max_rank'],r['index'],r['bit_offset'],r['bit_width'],r['spec']) for r in rows if r['node_id'])+'\nON DUPLICATE KEY UPDATE max_rank=VALUES(max_rank),layout_index=VALUES(layout_index),bit_offset=VALUES(bit_offset),bit_width=VALUES(bit_width),spec=VALUES(spec);\n'
    (out/'node_reference.sql').write_text(sql,encoding='utf-8')
    (out/'layout.json').write_text(json.dumps(dict(version=1,capacity=256,bits=count,hash=digest,nodes=rows),indent=2),encoding='utf-8')
    declarations='\n'.join(' DECLARE r%d INT DEFAULT 0;'%r['index'] for r in rows)+'\n'
    reads=''
    for r in rows:
        if r['node_id']:
            reads+=" SELECT COALESCE(MAX(rank_value),0) INTO r%d FROM JSON_TABLE(p_nodes,'$[*]' COLUMNS(id BIGINT PATH '$[0]',rank_value INT PATH '$[1]')) j WHERE id=%d;\n"%(r['index'],r['node_id'])
    (out/'node_sql_variables.inc.sql').write_text(declarations,encoding='utf-8')
    (out/'node_sql_reads.inc.sql').write_text(reads,encoding='utf-8')
    return rows

if __name__=='__main__':generate(Path(sys.argv[1]),Path(sys.argv[2]))
